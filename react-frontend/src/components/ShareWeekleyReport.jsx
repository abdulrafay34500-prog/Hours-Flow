import '../CSS-Files/shareWeekletreport.css'
import html2canvas from 'html2canvas';

function ShareWeekleyReport({employes , weekDays , months , dayNames , crossWeekleyReport}) {
     let weekFirstdate=new Date(weekDays[0])
     let weekLastdate=new Date(weekDays[6])
     let year=new Date(weekDays[0])

    return(
        <div className="shared-weekley-report-background">
            <div className="report-container js-sharing-weekley-report-container">
                <div className="report-header">
                    <div>
                        <h1>Weekly Shift Assignment</h1>
                        <p>{weekFirstdate.getDate()} {months[weekFirstdate.getMonth()]} - 
                            {weekLastdate.getDate()} {months[weekLastdate.getMonth()]} 
                            
                        </p>
                        <h4>
                            { year.getFullYear()}
                        </h4>
                    </div>

                    <div className="brand">HOURS FLOW</div>
                    </div>

                    <div className="table-wrapper">
                    <table className="shift-table">

                        <thead>
                        <tr>
                        <th>Employees</th>
                            {<DatesHeader weekDays={weekDays}  dayNames={dayNames}  months={months} /> }          
                        </tr>
                        </thead>

                        <tbody>

                        
                         {employes.map((employ)=>(
                            <ShowingEmployHours key={employ.id} employ={employ}  weekDays={weekDays} />
                         ))}

                        
                        </tbody>
                    </table>
                    </div>

                    <div className="report-footer">
                    <p>Weekly Total: <strong>{gettingWeekleyTotal(employes,weekDays)}</strong></p>
                    <p>Generated by Hours Flow</p>
                    </div>
                    <div className="weekley-cross-sighn" onClick={()=>crossWeekleyReport(false)}> 
                         ✖  
                    </div>
                    <button className="js-share-whatsapp" onClick={()=>shareReportFun()}>
                        <i data-lucide="share-2"></i>
                        Share Report
                    </button>
             
                    

            </div>                
         </div> 
    )
}
function ShowingEmployHours({employ , weekDays}) {
    return(
        <>
        
        <tr key={employ.id}>
            <td className="employee-name">{employ.name}</td>
            {weekDays.map((weekday ,index)=>{
                 return(
                     <td key={index}>
                        <div className={employ.Hours[weekday] ? 'shift' : 'off'} >
                        <span>{employ.Hours[weekday]
                            ? asigningShiftHours(employ  , weekday)|| 'Hours not set '
                            : ''}</span>
                        <small>{employ.Hours[weekday] ? `${employ.Hours[weekday]} hrs` : 'Off'}</small>
                        </div>
                    </td>
                 )
            })}
        </tr>    
                
           
        </>
    )
    
}
function asigningShiftHours(employ , weekday){
  let morningshift12hrs='3am - 3pm'
  let morningshift9hrs='6am - 3pm'
  let eveningshift12hrs='3pm - 3am'
  let eveningshift9hrs='3pm - 12am'
  let eveningshift11hrs='3pm - 2am'


  if(employ.shiftType === 'Morning' && employ.Hours[weekday] == 12){
    return  morningshift12hrs
  }else  if(employ.shiftType === 'Morning' && employ.Hours[weekday] == 9){
    return  morningshift9hrs
  }else if(employ.shiftType === 'Evening' && employ.Hours[weekday] == 12){
    return  eveningshift12hrs
  }else  if(employ.shiftType === 'Evening' && employ.Hours[weekday] == 9){
    return  eveningshift9hrs
  }else  if(employ.shiftType === 'Evening' && employ.Hours[weekday] == 11){
    return  eveningshift11hrs
  }
 
}
function DatesHeader({weekDays , dayNames , months}){
  return(
     <>
        {weekDays.map((days)=>{
            let date=new Date(days)
            return(
                <th key={days}>
                {dayNames[date.getDay()]} {date.getDate()}
                </th>
            )
        })}
    </>
  )
 

  
}
function gettingWeekleyTotal(employWithHours,weekDays) {
  let totalHours=0
  employWithHours.forEach((emp)=>{
   
    weekDays.forEach((days ,index)=>{
       totalHours+=emp.Hours[days] || 0 ;
    })
    
  })
  
  return totalHours;
} 
async function shareReportFun() {

    const report = document.querySelector(
        '.js-sharing-weekley-report-container'
    );

    const canvas = await html2canvas(report, {
        scale: 2,
        backgroundColor: '#ffffff',

        ignoreElements: (element) =>
            element.classList.contains('js-share-whatsapp') ||
            element.classList.contains('weekley-cross-sighn')
    });

    // Convert canvas to Blob
    canvas.toBlob(async (blob) => {

        if (!blob) return;

        // Create image file
        const file = new File(
            [blob],
            'WeeklyReport.png',
            { type: 'image/png' }
        );

        // Share image
        if (navigator.canShare?.({ files: [file] })) {

            try {
                await navigator.share({
                    files: [file],
                    title: 'HourFlow Weekly Report'
                });
            } catch (error) {
                console.log(error);
            }

        } else {
            // Download if sharing isn't supported
            const link = document.createElement('a');
            link.href = canvas.toDataURL('image/png');
            link.download = 'WeeklyReport.png';
            link.click();
        }

    }, 'image/png');
}  
export default ShareWeekleyReport